/**
 * 과목명(name)을 인자로 받아 과목 상세 정보를 생성/반환하는 헬퍼 함수
 * 데이터베이스에 없더라도 2022 개정 교육과정 기준에 맞게 지능적으로 생성합니다.
 */
export function getSubjectDetail(subjectName: string): SubjectDetail {
  const trimmed = subjectName.trim();
  
  // 1. 직접 매칭 확인
  if (SUBJECT_DETAILS[trimmed]) {
    const raw = SUBJECT_DETAILS[trimmed];
    const evalInfo = getSubjectEvaluationInfo(trimmed, raw.area, raw.type as SelectionType);
    return {
      name: trimmed,
      area: raw.area || '보통교과',
      type: raw.type || '선택',
      credits: raw.credits || (['체육', '예술', '교양'].includes(raw.area || '') ? '기본 3학점' : '기본 4학점'),
      evaluation: evalInfo.evaluationMethod,
      description: raw.description || `${trimmed} 과목은 2022 개정 교육과정에 따른 교과 학습 내용을 심화·탐구하는 과목입니다.`,
      coreIdeas: raw.coreIdeas || ['해당 교과의 핵심 개념을 깊이 있게 이해하고 비판적 사고력과 문제 해결력을 함양합니다.'],
      contentElements: raw.contentElements || [
        { category: '주요 학습 영역', items: ['교과 기초 개념 탐구', '원리와 법칙의 적용', '실생활 연계 심화 탐구'] }
      ],
      relatedMajors: raw.relatedMajors || ['관련 계열 학과 전체', '자율전공학부'],
      relatedCareers: raw.relatedCareers || ['전문 연구원', '교육자', '산업체 전문가'],
      connections: raw.connections
    };
  }

  // 1.5 학기제 교차 과목 확인 (예: 기술·가정↔음악, 정보↔미술)
  if (isExchangeSubject(trimmed)) {
    const parts = parseExchangeSubject(trimmed);
    if (parts.length > 0) {
      const primaryDetail = getSubjectDetail(parts[0]);
      return {
        ...primaryDetail,
        name: trimmed,
        description: `[학기제 교차 편성 과목: ${parts.join(' ↔ ')}]\n1학기와 2학기에 걸쳐 학급별로 교차 이수하는 과목입니다. 안내 팝업 상단 탭에서 각 과목별(${parts.join(', ')}) 세부 교육과정 안내를 개별 확인하실 수 있습니다.\n\n${primaryDetail.description}`
      };
    }
  }

  // 2. 부분 일치 검색 (예: 공통수학 -> 공통수학1 등)
  const key = Object.keys(SUBJECT_DETAILS).find(k => k === trimmed || trimmed.includes(k) || k.includes(trimmed));
  if (key && SUBJECT_DETAILS[key]) {
    const raw = SUBJECT_DETAILS[key];
    const evalInfo = getSubjectEvaluationInfo(trimmed, raw.area, raw.type as SelectionType);
    return {
      name: trimmed,
      area: raw.area || '보통교과',
      type: raw.type || '선택',
      credits: raw.credits || '기본 4학점',
      evaluation: evalInfo.evaluationMethod,
      description: raw.description || `${trimmed} 과목은 2022 개정 교육과정에 따른 탐구 과목입니다.`,
      coreIdeas: raw.coreIdeas || ['학습자의 진로와 흥미에 부합하는 심화 지식을 습득하고 탐구 역량을 발전시킵니다.'],
      contentElements: raw.contentElements || [
        { category: '주요 내용', items: ['교과 핵심 지식·이해', '사례 분석 및 탐구 실습'] }
      ],
      relatedMajors: raw.relatedMajors || ['관련 계열 학과'],
      relatedCareers: raw.relatedCareers || ['해당 분야 전문가'],
      connections: raw.connections
    };
  }

  // 3. 교과군 및 유형 추론 Fallback
  let inferredArea = '기타';
  for (const [areaName, list] of Object.entries(SUBJECT_AREAS)) {
    if (list.some(s => s.trim() === trimmed || trimmed.includes(s.trim()))) {
      inferredArea = areaName;
      break;
    }
  }

  const inferredType = (SUBJECT_TYPES[trimmed] || '일반') as SelectionType;
  const evalInfo = getSubjectEvaluationInfo(trimmed, inferredArea, inferredType);
  const isPEorArt = inferredArea === '체육' || inferredArea === '예술' || inferredArea === '교양';

  return {
    name: trimmed,
    area: inferredArea,
    type: inferredType,
    credits: isPEorArt ? '기본 3학점 (2~4학점)' : '기본 4학점 (3~5학점)',
    evaluation: evalInfo.evaluationMethod,
    description: `<${trimmed}>은 2022 개정 교육과정에 편성된 ${inferredArea} 교과의 ${inferredType} 선택 과목입니다. 학생의 자기주도적 학업 역량과 진로 맞춤형 전문성을 신장시키는 데 기여합니다.`,
    coreIdeas: [
      `${inferredArea} 교과의 학문적 원리와 체계를 깊이 있게 탐구하고 실생활 및 전공 분야와 연계합니다.`,
      `다양한 탐구 및 실습 과정을 통해 비판적 사고력과 융합적 문제해결 능력을 함양합니다.`
    ],
    contentElements: [
      { category: '지식·이해', items: [`${trimmed}의 주요 개념 및 학문적 원리`, '주제별 심화 탐구 및 분석'] },
      { category: '과정·기능', items: ['자료 분석 및 비판적 해석', '프로젝트 수행 및 탐구 보고서 작성'] },
      { category: '가치·태도', items: ['학문적 호기심과 자기주도적 학습 태도', '사회적 기여 및 진로 개척 의지'] }
    ],
    relatedMajors: inferredArea === '과학' 
      ? ['자연과학계열', '공학계열', '의약학계열']
      : inferredArea === '수학'
      ? ['이공계열', '상경계열', '데이터과학부']
      : inferredArea === '사회'
      ? ['사회과학계열', '인문학부', '사범대학']
      : inferredArea === '국어' || inferredArea === '영어'
      ? ['어문학부', '미디어커뮤니케이션학과', '국제학부']
      : ['관련 전공 계열 학부'],
    relatedCareers: ['전문 연구원', '공공기관 및 기업 전문가', '교육자', '융합 산업 종사자']
  };
}
